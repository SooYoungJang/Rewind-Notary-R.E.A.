"""Fixed-tick replay of the walking input at a side contact on the way to a wave target."""
from dataclasses import dataclass
import math
import re

from validate_fixed_surface_route import Face, fixed_edges, link, paths_from, room_faces, steer
from validate_level_step1 import contains, number
from validate_story_bout import Actor


@dataclass(frozen=True)
class SideJumpRule:
    delay: float
    slop: float = 0
    launch_only: bool = False
    enabled_only: bool = False


RAY_ONLY = SideJumpRule(math.inf)  # 2e46f6f2
IMMEDIATE = SideJumpRule(0)        # c26b5278


def read_side_rule(bot):
    walk = bot.split('private bool Walk(')[1].split('private void SeekFloor')[0]
    if '|| TouchingStepAhead(facing)' in walk:
        return IMMEDIATE
    if 'BlockedAtStep(facing)' not in walk:
        return RAY_ONLY
    return SideJumpRule(number(bot, 'BlockedWalkSeconds'),
                        number(bot, 'BlockedWalkSlop'), 'approachingLaunch && BlockedAtStep(facing)' in walk,
                        'hit.enabled &&' in walk)


class WalkContact:
    def __init__(self, rule):
        self.rule = rule
        self.last_tick = -2
        self.identity = None
        self.anchor = self.since = 0

    def jump(self, tick, dt, x, direction, face, *, launch, enabled):
        if (face is None or (self.rule.launch_only and not launch)
                or (self.rule.enabled_only and not enabled)):
            return False
        if (tick != self.last_tick + 1 or self.identity != (face, direction)
                or abs(x - self.anchor) > self.rule.slop):
            self.anchor, self.since = x, tick
        self.last_tick, self.identity = tick, (face, direction)
        return (tick - self.since) * dt >= self.rule.delay


def velvet_deck(room, layout, bridge_open):
    """Authored fixed faces and the walkable blocks generated by BuildRoom."""
    boundary = room.get('eastBoundary')
    walls = boundary or int(re.search(r'Room.eastBoundary > 0 \? Room.eastBoundary : (\d+)', layout)[1])
    deck = room_faces(dict(room, eastBoundary=walls))
    if boundary:
        return deck + [Face('floor', -4, boundary, -2, 0, False)]

    center = float(re.search(r'Block\("floor", HasBridge \? (\d+) :', layout)[1])
    width = float(re.search(r'-1, HasBridge \? (\d+) :', layout)[1])
    deck.append(Face('floor', center - width / 2, center + width / 2, -2, 0, False))
    for name in ('east', 'latch_bridge') if bridge_open else ('east',):
        args = re.search(r'Block\("' + name + r'", ([-.\df, ]+), (?:stone|Color.gray), true\)', layout)[1]
        x, y, w, h = (float(v.strip().rstrip('f')) for v in args.split(','))
        deck.append(Face(name, x - w / 2, x + w / 2, y - h / 2, y + h / 2, False))
    return deck


def replay_gallery(room, layout, physics, bot, motor, sword, rule, limit, start=None):
    jump, gravity, dt, speed, _, _, radius, height, tolerance = physics
    deck = velvet_deck(room, layout, bridge_open=False)
    floor = next(f for f in deck if f.name == 'floor')
    edges = fixed_edges(deck, physics)
    group = next(g for g in room['roster'] if g['id'] == 'sword_latch')
    target = next(p for p in room['placements'] if p['id'] == group['placementIds'][0])
    goal, = (f for f in edges if f.left <= target['x'] <= f.right and abs(f.top - target['y']) < .5)
    # Begin on the final approach, just beyond the other targets' activation zones.
    start_x = max(p['active']['x'] + p['active']['width'] for p in room['placements'] if p != target) + radius
    actor = Actor(start_x, floor.top, 5, vx=speed, floor=floor) if start is None else start
    start_feet = [round(actor.x, 3), round(actor.y, 3)]
    start_velocity = [actor.vx, actor.vy]
    aim = float(re.search(r'if \(range > ([.\d]+)f\) \{ Walk', bot)[1])
    swing = [float(v.strip().rstrip('f')) for v in re.search(r'new AttackSpec\(([^)]+)\)', motor)[1].split(',')]
    hold = float(re.search(r'jumpUntil = Time.time \+ ([.\d]+)f', bot)[1])
    contact = WalkContact(rule)
    step = None
    hold_until = -1
    held_last = False
    swing_tick = cut_tick = None
    remaining = group['segments']
    hops, landings = [], []
    first_contact = None
    low_hops = side_samples = 0
    for tick in range(round(limit / dt)):
        now = round(tick * dt, 6)
        axis = 0
        space, walk = now < hold_until, False
        dx = target['x'] - actor.x
        if actor.floor == goal:
            step = None  # ReachedCombatSurface hands the keyboard to Aim/FightTarget.
            if swing_tick is not None:
                age = (tick - swing_tick) * dt
                if age < sword['stepSeconds']:
                    axis = actor.face * sword['stepSpeed'] / speed
                if age >= swing[1]:
                    blade = actor.x + actor.face * swing[3]
                    if (contains(target['active'], actor.x, actor.y)
                            and abs(blade - target['x']) <= swing[4] / 2 + .4
                            and abs(actor.y + 1 - target['y'] - .9) <= swing[5] / 2 + .9):
                        remaining -= 1
                        cut_tick = tick
                    break  # A missed first strike must fail this one-segment fixture.
            elif abs(dx) > aim:
                axis, walk = (1 if dx > 0 else -1), True
            elif abs(dx) > .06 and dx * actor.face <= 0:
                axis = 1 if dx > 0 else -1
            else:
                swing_tick = tick
        elif actor.floor:
            parents = paths_from(edges, actor.floor)
            child = goal
            while parents[child] != actor.floor:
                child = parents[child]
            step = link(deck, actor.floor, child, physics)
            assert step[2], 'The grounded latch is approached by walking off the upper tread'
            axis = step[2]
        elif step:
            dx = step[1] - actor.x
            axis = 0 if abs(dx) <= tolerance else (1 if dx > 0 else -1)

        if walk:
            # An effector can disable the collision response at a vertical side. The
            # historical predicate inspected the manifold even while D advanced the body.
            side = None
            ray = False
            for face in deck:
                gap = face.left - actor.x if axis > 0 else actor.x - face.right
                if (0 < gap <= radius and actor.y + radius < face.top <= actor.y + height
                        and face.bottom < actor.y + height - radius):
                    side = face
                ray |= 0 < gap <= .95 and face.bottom <= actor.y + .18 <= face.top
            side_samples += side is not None
            if side is not None and first_contact is None:
                first_contact = dict(tick=tick, collider=side.name, x=round(actor.x, 3), vx=actor.vx,
                                     enabled=not side.one_way)
            side_jump = contact.jump(tick, dt, actor.x, axis, side, launch=False,
                                     enabled=side is not None and not side.one_way)
            if ray or side_jump:
                if ray:
                    low_hops += 1
                else:
                    hops.append(tick)
                hold_until, space = now + hold, True
                actor.vy, actor.floor = jump, None
        if not space and held_last and actor.vy > 0:
            actor.vy *= .5
        held_last = space
        if axis:
            actor.face = 1 if axis > 0 else -1
        actor.vx = speed * axis if actor.floor else steer(actor.vx, axis, physics)
        previous = actor.floor
        actor.advance(deck, radius, gravity, dt)
        if previous is None and actor.floor:
            landings.append((tick + 1, actor.floor.name))

    else:
        now = limit
    return dict(startFeet=start_feet, startVelocity=start_velocity, seconds=round(now, 2),
                endFeet=[round(actor.x, 3), round(actor.y, 3)], targetSupport=goal.name,
                firstSide=first_contact, sideSamples=side_samples, sideJumpTicks=hops, rayJumps=low_hops,
                firstLandings=landings[:4], landings=len(landings), swordTick=swing_tick,
                cutTick=cut_tick, remaining=remaining)


def velvet_pairs(verify, rooms, layout, physics):
    # With the latch bridges deployed the navigation graph includes their colliders.
    # An elevated arrival shelf also has an incoming door edge from the previous room.
    graphs = {r['id']: fixed_edges(velvet_deck(r, layout, bridge_open=True), physics) for r in rooms}
    gallery = next(r for r in rooms if r['id'] == 'velvet_03_gallery')
    loom = next(r for r in rooms if r['id'] == 'velvet_02_loom')
    out = next(d for d in gallery['exits'] if d['room'] == loom['id'])
    back = next(d for d in loom['exits'] if d['room'] == gallery['id'])

    def door_face(room, door):
        face, = (f for f in graphs[room['id']] if f.left < door['x'] < f.right
                 and contains(door['approach'], door['x'], f.top + .05))
        return face

    def arrival(room, door):
        mark = next(f for f in room['floors'] if f['id'] == door['destinationFloor'])
        return next(f for f in graphs[room['id']] if f.name == mark['surface'] and f.left < mark['x'] < f.right)

    gallery_exit, shelf = door_face(gallery, out), arrival(gallery, back)
    can_return = (not out['gate'] and back['gate'] == 'loom_bridge' and door_face(loom, back) in
                  paths_from(graphs[loom['id']], arrival(loom, out)))
    results = {}
    for room_id, edges in graphs.items():
        fixed = via_door = 0
        for a in edges:
            reachable = paths_from(edges, a)
            fixed += len(reachable) - 1
            via_door += sum(room_id == gallery['id'] and b == shelf and can_return and gallery_exit in reachable
                            for b in edges if b not in reachable)
        total = len(edges) * (len(edges) - 1)
        verify(fixed + via_door == total, room_id + ' / every directed fixed-face pair including authored door arrivals')
        results[room_id] = dict(fixed=fixed, viaArrivalDoor=via_door, total=total)
    return results


def validate_side_inputs(verify, rule, physics):
    # A solid collision at a launch point lets us exercise each guard independently.
    dt, speed = physics[2:4]
    wait = math.ceil(rule.delay / dt) if math.isfinite(rule.delay) else 10
    ticks = range(wait + 1)
    split = wait // 2

    def samples(window, direction, face='deck', speed_x=0):
        return [(t, t * dt * speed_x, direction, face) for t in window]

    def fires(sequence, launch=True, enabled=True):
        contact = WalkContact(rule)
        return [t for t, x, direction, face in sequence
                if contact.jump(t, dt, x, direction, face, launch=launch, enabled=enabled)]

    for direction in (-1, 1):
        parked = samples(ticks, direction)
        moving = samples(ticks, direction, speed_x=direction * speed)
        verify(fires(parked) == [wait] and not fires(moving),
               'run 17 / a held direction must stop advancing before side escape ' + str(direction))
        verify(not fires(parked, launch=False) and not fires(parked, enabled=False),
               'run 17 / final positioning and disabled contacts never arm side escape ' + str(direction))
        first, second = parked[:split], ticks[split:]
        verify(not fires(first + parked[split + 1:]) and not fires(first + samples(second, -direction)) and
               not fires(first + samples(second, direction, face='next')),
               'run 17 / release, reversal and changed obstacle restart the wait ' + str(direction))


def validate_gallery(verify, rooms, scripts, physics, sword, archetypes):
    room = next(r for r in rooms if r['id'] == 'velvet_03_gallery')
    bot, motor = scripts['FirstDepartureBot'], scripts['CombatMotor2D']
    traversal = scripts['ClockTraversal']
    dt = physics[2]
    steps = re.search(r'enum PlaytestStep \{([^}]+)\}', bot)[1].strip().split(', ')
    limits = re.search(r'int\[\] Limits = \{([^}]+)\}', bot)[1].strip().split(', ')
    limit = int(limits[steps.index('Velvet')])
    layout = scripts['RepresentativeRoomLayout']
    rule = read_side_rule(bot)
    latch = next(g for g in room['roster'] if g['id'] == 'sword_latch')
    kind = next(a for a in archetypes if a['id'] == latch['id'])
    verify(kind['mechanism'] and kind['gate'] == 'device' and latch['segments'] == 1
           and not latch.get('setupSkill') and not latch.get('skillOnly') and sword['stage'] == 1
           and '!Ready(now)) return false;' in scripts['WaveTargetState']
           and 'entry.zone.Contains(player.Body.position)' in scripts['StoryTerrain']
           and 'new Vector3(0.8f, 1.8f, 2)' in scripts['WaveTarget2D'],
           'run 17 / one active gallery mechanism segment takes the first ordinary sword contact')
    verify(limit == 240 and 'if (face == null || ReachedCombatSurface(face, at.x)) FightTarget(target);' in bot
           and 'if (range > 1.15f) { Walk(x, 1.15f); return false; }' in bot
           and 'effector.useOneWay = true;' in scripts['StoryTerrain']
           and 'effector.surfaceArc = 150f;' in scripts['StoryTerrain'],
           'run 17 / ordinary wave selection and Aim walk through the one-way gallery terrain')
    verify(rule.launch_only and rule.enabled_only and 0 < rule.slop < physics[3] * dt and rule.delay >= 2 * dt
           and 'bool approachingLaunch = false' in bot
           and sum(s.count('approachingLaunch: true') for s in scripts.values()) == 1
           and 'if (here == goal) { ClearStep(); return Walk(x, tolerance); }' in traversal
           and all(s in bot for s in ('other != blockedBy', 'facing != blockedDirection',
                                       'blockedFrame != Time.frameCount - 1', 'Mathf.Abs(x - blockedX) > BlockedWalkSlop',
                                       'blockedSince = Time.fixedTime;', 'blockedX = x;', 'blockedFrame = Time.frameCount;',
                                       'blockedBy = other;', 'blockedDirection = facing;',
                                       'return Time.fixedTime - blockedSince >= BlockedWalkSeconds;')),
           'run 17 / side escape requires continuous physics-time blockage on the route to a launch')
    def run(policy, start=None):
        return replay_gallery(room, layout, physics, bot, motor, sword, policy, limit, start)

    prior, regression, fixed = run(RAY_ONLY), run(IMMEDIATE), run(rule)
    verify(prior['cutTick'] is not None and prior['remaining'] == 0 and prior['sideSamples'] > 0
           and prior['targetSupport'] == 'floor' and not prior['rayJumps'] and not prior['sideJumpTicks'],
           'run 17 / ray-only bot passes the first tread on the floor and cuts the active latch')
    hops = regression['sideJumpTicks']
    verify(len(hops) > 1 and regression['firstSide'] == prior['firstSide']
           and regression['firstSide']['vx'] == physics[3] and hops[0] == regression['firstSide']['tick']
           and [s for _, s in regression['firstLandings'][:2]] ==
           [regression['firstSide']['collider'], regression['targetSupport']]
           and regression['seconds'] == limit and regression['remaining'] == 1
           and regression['swordTick'] is None and not regression['rayJumps'],
           'run 17 / immediate side jumps repeatedly land on the tread and descend before final aim')
    verify(fixed == prior and fixed['cutTick'] is not None,
           'run 17 / current shared Walk reaches the grounded latch and cuts on the historical tick')
    # Run 17 has no vertical velocity sample. Test recovery in either direction from its saved feet.
    def from_snapshot(policy, vy):
        return run(policy, Actor(20.138248443603516, 1.8129606246948242, 5, vy=vy))

    recoveries = []
    for vy in (-2, 2):
        before, after = from_snapshot(IMMEDIATE, vy), from_snapshot(rule, vy)
        verify(before['remaining'] == 1 and before['swordTick'] is None and len(before['sideJumpTicks']) > 1
               and after['remaining'] == 0 and after['swordTick'] < after['cutTick'] and not after['sideJumpTicks']
               and after['firstLandings'][-1][1] == fixed['targetSupport'],
               f'run 17 / airborne failure position reaches the latch after narrowing the rule at vy={vy}')
        recoveries.append(dict(startVy=vy, immediateJumps=len(before['sideJumpTicks']), after=after))

    validate_side_inputs(verify, rule, physics)
    return dict(fixedDt=dt, limitSeconds=limit, beforeSideRule=prior, immediateSideRule=regression,
                after=fixed, recoveryFromSnapshot=recoveries,
                velvetOrderedPairs=velvet_pairs(verify, rooms, layout, physics))
